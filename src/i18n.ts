export type MessageKey = keyof typeof en;
export type Translate = (key: MessageKey, values?: MessageValues) => string;

const localeStorageKey = "gitcat-locale";

export function readLocale(): Locale {
  try {
    const saved = localStorage.getItem(localeStorageKey);
    if (saved === "en" || saved === "es") return saved;
  } catch { /* unavailable storage uses the system default */ }
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
}

export function writeLocale(locale: Locale) {
  try { localStorage.setItem(localeStorageKey, locale); } catch { /* a full quota must not break the interface */ }
}

export function localeTag(locale: Locale) { return locale === "es" ? "es-ES" : "en-US"; }

export function translate(locale: Locale): Translate {
  const messages = locale === "es" ? es : en;
  return (key, values = {}) => {
    const template = messages[key] ?? en[key] ?? key;
    return template.replace(/\{\{(\w+)\}\}/g, (_match, name: string) => String(values[name] ?? `{{${name}}}`));
  };
}

export { localeStorageKey };
